/// Aplica [kCatalogMusclePatches] a los registros del catálogo en sitio.
/// `muscle_group` se deriva del primer secundario, como en el dataset.
void applyCatalogPatches(List<Map<String, dynamic>> records) {
  for (final record in records) {
    final patch = kCatalogMusclePatches[record['id']];
    if (patch == null) continue;
    record['target'] = patch.target;
    record['secondary_muscles'] = patch.secondaryMuscles;
    record['muscle_group'] = patch.secondaryMuscles.first;
  }
}
